-- 2026-10-06, taken from pg_dump on Postgres 16. Databases created before Flyway are
-- identical to this and are adopted as V1 via spring.flyway.baseline-on-migrate.
-- Free-text and list columns are text / text[] on purpose (real values exceed 255
-- chars); UpdaterComponentApplicationIT.freeTextColumnsAreNotLengthLimited guards this.

CREATE TABLE source_version (
    feed_id         varchar(255) NOT NULL,
    content_hash    varchar(255),
    last_checked_at timestamp(6) with time zone,
    last_updated_at timestamp(6) with time zone,
    CONSTRAINT source_version_pkey PRIMARY KEY (feed_id)
);

