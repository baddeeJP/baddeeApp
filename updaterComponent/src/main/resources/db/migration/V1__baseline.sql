-- Kanji (KanjiDic2 / RADKFILE / KanjiVG)
CREATE TABLE kanji (
    "character"       varchar(255) NOT NULL,
    classical_radical integer,
    codepoint         varchar(255),
    frequency         integer,
    grade             integer,
    jlpt              integer,
    joyo              boolean,
    kunyomi           text[],
    meanings          text[],
    nanori            text[],
    onyomi            text[],
    stroke_count      integer,
    stroke_paths      text[],
    CONSTRAINT kanji_pkey PRIMARY KEY ("character")
);

CREATE TABLE radical (
    "character"  varchar(255) NOT NULL,
    stroke_count integer,
    CONSTRAINT radical_pkey PRIMARY KEY ("character")
);

CREATE TABLE kanji_radical (
    kanji   varchar(255) NOT NULL,
    radical varchar(255) NOT NULL,
    CONSTRAINT kanji_radical_pkey PRIMARY KEY (kanji, radical),
    CONSTRAINT fk39amf2uckytgcqvyd8qcppgdg FOREIGN KEY (kanji) REFERENCES kanji ("character"),
    CONSTRAINT fkihyxqgp0702btf0uw5rpfolwj FOREIGN KEY (radical) REFERENCES radical ("character")
);

